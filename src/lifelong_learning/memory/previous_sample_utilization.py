from __future__ import annotations

import json
from pathlib import Path

from src.lifelong_learning.core.models import (
    ChatMessage, EvaluationOutcome, Role, SampleStatus, Session
)


class PreviousSampleUtilizationMemory:
    """Save and reuse the recently successfully completed sessions"""

    def __init__(self, utilized_sample_count: int) -> None:
        if utilized_sample_count <= 0:
            raise ValueError("Utilized sample count must be positive")
        
        self.utilized_sample_count = (utilized_sample_count)
        self.utilized_session_list: list[Session] = []

    @property
    def session_count(self) -> int:
        return len(self.utilized_session_list)
    
    @property
    def sample_index_list(self) -> list[str]:
        return [
            session.sample_index
            for session in self.utilized_session_list
        ]
    
    def observe(self, session: Session) -> bool:
        """Only completed & correct Session can input PSU memory"""
        accepted = (
            session.sample_status == SampleStatus.COMPLETED
            and session.evaluation_record.outcome == EvaluationOutcome.CORRECT
        )

        if not accepted: return False

        self.utilized_session_list.append(session.model_copy(deep=True))

        # Without similarity calculation
        if (len(self.utilized_session_list) > self.utilized_sample_count):
            self.utilized_session_list.pop(0)
        
        return True
    
    @staticmethod
    def _get_role_name(role: Role) -> str:
        if role == Role.USER:
            return "user"
        return "assistant"
    
    @classmethod
    def _serialize_session(cls, session:Session) -> str:
        """Transfer a success Session into PSU texture
        The first three messages are:
        0. Rule
        1. Agent respponse "OK"      
        2. Current sample problem  
        """
        message_list = session.chat_history.messages
        if len(message_list) < 3:
            question = ""
        else:
            question = message_list[2].content

        trajectory_line_list = [
            (
                f"{cls._get_role_name(message.role)}: "
                f"{message.content}"
            )
            for message in message_list[3:]
        ]

        trajectory_text = "\n".join(trajectory_line_list)
        return (
            f"Question {question}:\n"
            f"{trajectory_text}"
        )
    
    def build_prompt_text(self) -> str:
        """Construct all the empirical text that will be inserted into the PSU prompt"""
        example_text = "\n"

        for session in self.utilized_session_list:
            example_text += self._serialize_session(session=session)

        return example_text
    
    @staticmethod
    def sanitize_agent_response(agent_response: ChatMessage) -> ChatMessage:
        """Delete the subsequent user messages forged by the model under the induction of the PSU example.
        For example, the model might generate simultaneously:
        Action: Operation
        ...
        user: []
        The actual user message must be generated by the task environment and cannot be forged by the model.
        """
        counterfeit_user_marker = "\nuser: "
        marker_position = (
            agent_response.content.find(counterfeit_user_marker)
        )
        if marker_position == -1:
            return agent_response
        return ChatMessage(
            role=agent_response.role,
            content=agent_response.content[:marker_position]
        )
    
    def save_state(self, file_path: Path) -> None:
        """Save current PSU memory to JSON format"""
        """将当前 PSU 记忆保存为 JSON。"""
        file_path = Path(file_path)
        file_path.parent.mkdir(parents=True, exist_ok=True)

        with file_path.open("w", encoding="utf-8") as file:
            json.dump(
                [
                    session.model_dump(mode="json")
                    for session
                    in self.utilized_session_list
                ],
                file,
                ensure_ascii=False,
                indent=2,
            )